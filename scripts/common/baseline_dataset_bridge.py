"""Small adapters that let related baselines reuse Scaffold-Fast datasets.

The related-method repos use a mix of PyG ``Data`` objects, dense adjacency
matrices, and local Planetoid files.  This module keeps the compatibility glue
in one place while delegating actual dataset loading to
``scaffold_gnn.utils.dataset``.
"""

