SCAFFOLD_CLUSTER_COUNTS = {
    "reddit": 1500,
    "ogbn-products": 1500,
    "ogbn-arxiv": 500,
    "ogbn-proteins": 1000,
    "pokec": 8000,
}


def support_graph_root() -> Path:
    env_root = os.environ.get("SUPPORT_GRAPH_ROOT")
    if env_root:
        return Path(env_root).expanduser().resolve()
    return Path(__file__).resolve().parents[2]


def ensure_support_graph_on_path() -> None:
    root = str(support_graph_root())
    if root not in sys.path:
        sys.path.insert(0, root)


def canonical_baseline_dataset_name(name: str) -> str:
    return DATASET_ALIASES.get(str(name).strip().lower(), str(name).strip().lower())


def scaffold_cluster_count(dataset_name: str) -> int:
    canonical = canonical_baseline_dataset_name(dataset_name)
    return int(SCAFFOLD_CLUSTER_COUNTS.get(canonical, 64))


def _torch_load_trusted_cache(path: Path | str):
    # These files are generated by this baseline runner under the configured
    # cache directory. PyTorch 2.6 defaults torch.load to weights_only=True,
    # which rejects PyG Data objects saved in these local cache files.
    return torch.load(path, map_location="cpu", weights_only=False)


def _idx_to_mask(idx: torch.Tensor, num_nodes: int) -> torch.Tensor:
    idx = torch.as_tensor(idx)
    if idx.dtype == torch.bool:
        if idx.numel() != num_nodes:
            raise ValueError(f"Boolean mask has {idx.numel()} entries for {num_nodes} nodes")
        return idx.clone().bool()
    mask = torch.zeros(num_nodes, dtype=torch.bool)
    mask[idx.long()] = True
    return mask


def _split_to_masks(split: Dict[str, torch.Tensor], num_nodes: int) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    return (
        _idx_to_mask(split["train"], num_nodes),
        _idx_to_mask(split["valid"], num_nodes),
        _idx_to_mask(split["test"], num_nodes),
    )


def load_pyg_data(data_root: str, dataset_name: str) -> Tuple[Data, object]:
    """Return a PyG ``Data`` object with train/val/test masks."""
    ensure_support_graph_on_path()
    from scaffold_gnn.utils.dataset import canonical_split_fingerprint, load_dataset

    data_root = str(Path(data_root).expanduser().resolve())
    canonical_name = canonical_baseline_dataset_name(dataset_name)
    print(
        f"[DatasetSource] dataset={canonical_name} data_root={data_root} "
        f"method={os.environ.get('BASELINE_METHOD_NAME', 'shared')}",
        flush=True,
    )
    cached_partition = _load_cached_partition_data(data_root, dataset_name)
    if cached_partition is not None:
        return cached_partition, None

    dataset = load_dataset(data_root, canonical_name)
    graph, label = dataset[0]
    num_nodes = int(graph["num_nodes"])

    y = label
    if y is not None:
        y = torch.as_tensor(y)
        if y.dim() == 2 and y.size(1) == 1:
            y = y.view(-1)
        elif y.dim() > 1 and os.environ.get("BASELINE_FORCE_SINGLE_LABEL", "0") in ("1", "true", "TRUE", "yes"):
            print(
                "[baseline-label] converting multi-label targets to argmax single-label "
                "targets for compatibility smoke testing."
            )
            y = y.argmax(dim=-1)

    data = Data(
        x=torch.as_tensor(graph["node_feat"]).float(),
        edge_index=torch.as_tensor(graph["edge_index"]).long(),
        y=y,
        num_nodes=num_nodes,
    )
    if graph.get("edge_index_is_undirected_unique"):
        data.edge_index_is_undirected_unique = True
    if graph.get("edge_feat") is not None:
        data.edge_attr = torch.as_tensor(graph["edge_feat"])

    if hasattr(dataset, "load_fixed_splits"):
        split = dataset.load_fixed_splits()
        if isinstance(split, list):
            split = split[0]
    elif getattr(dataset, "train_idx", None) is not None:
        split = {
            "train": dataset.train_idx,
            "valid": dataset.valid_idx,
            "test": dataset.test_idx,
        }
    else:
        split = dataset.get_idx_split()

    data.train_mask, data.val_mask, data.test_mask = _split_to_masks(split, num_nodes)
    split_hash = canonical_split_fingerprint(
        {
            "train": data.train_mask,
            "valid": data.val_mask,
            "test": data.test_mask,
        }
    )
    data.canonical_dataset_name = canonical_name
    data.canonical_data_root = data_root
    data.canonical_split_fingerprint = split_hash
    print(
        f"[DatasetSplit] fingerprint={split_hash} "
        f"train={int(data.train_mask.sum())} valid={int(data.val_mask.sum())} "
        f"test={int(data.test_mask.sum())}",
        flush=True,
    )
    data = maybe_partition_for_smoke(data, data_root, dataset_name)
    return data, dataset


def maybe_partition_for_smoke(data: Data, data_root: str, dataset_name: str) -> Data:
    mode = os.environ.get("BASELINE_PARTITION_MODE", "none").strip().lower()
    if mode in ("", "none", "false", "0", "off"):
        return data

    canonical = canonical_baseline_dataset_name(dataset_name)
    if canonical == "cora" and "BASELINE_PARTITION_COUNT" not in os.environ:
        print("[baseline-partition] dataset=Cora uses full graph; skipping METIS partition.", flush=True)
        return data

    threshold = int(os.environ.get("BASELINE_PARTITION_MIN_NODES", "100000"))
    if mode == "auto" and int(data.num_nodes) <= threshold:
        return data

    cluster_count = int(os.environ.get("BASELINE_PARTITION_COUNT", scaffold_cluster_count(dataset_name)))
    cluster_id = int(os.environ.get("BASELINE_PARTITION_ID", "0"))
    max_nodes = int(os.environ.get("BASELINE_PARTITION_MAX_NODES", "12000"))
    if mode in ("sample", "safe", "node-sample", "nodesample", "random"):
        return _sample_partition_data(data, data_root, dataset_name, cluster_count, cluster_id, max_nodes)

    edge_sample_size = int(os.environ.get("BASELINE_PARTITION_EDGE_SAMPLE_SIZE", "5000000"))
    effective_edge_sample_size = edge_sample_size if edge_sample_size > 0 and data.edge_index.size(1) > edge_sample_size else 0
    cache_root = Path(os.environ.get("BASELINE_PARTITION_CACHE_ROOT", data_root))
    method = os.environ.get("BASELINE_METHOD_NAME", "shared").strip().lower() or "shared"
    cache_dir = cache_root / method / "partitions"
    cache_dir.mkdir(parents=True, exist_ok=True)
    sample_tag = f"_sample{effective_edge_sample_size}" if effective_edge_sample_size else ""
    cache_path = cache_dir / (
        f"{canonical}_parts{cluster_count}_n{int(data.num_nodes)}_e{int(data.edge_index.size(1))}{sample_tag}.pt"
    )

    if cache_path.exists():
        part = _torch_load_trusted_cache(cache_path)
    else:
        part = _metis_partition(data, cluster_count, effective_edge_sample_size)
        torch.save(part.cpu(), cache_path)

    unique_parts = torch.unique(part.cpu())
    if unique_parts.numel() == 0:
        return data

    chosen_part = int(unique_parts[cluster_id % unique_parts.numel()].item())
    node_idx = torch.where(part.cpu() == chosen_part)[0]
    if node_idx.numel() > max_nodes:
        node_idx = _balanced_partition_sample(data, node_idx, max_nodes)

    partitioned = _induce_partition_data(data, node_idx, dataset_name, cluster_count, chosen_part)
    data_cache_path = _partition_data_cache_path(data_root, dataset_name)
    if data_cache_path is not None:
        torch.save(partitioned, data_cache_path)
    return partitioned


def _sample_partition_data(
    data: Data,
    data_root: str,
    dataset_name: str,
    cluster_count: int,
    cluster_id: int,
    max_nodes: int,
) -> Data:
    data_cache_path = _partition_data_cache_path(data_root, dataset_name)
    if data_cache_path is not None and data_cache_path.exists():
        cached = _torch_load_trusted_cache(data_cache_path)
        print(f"[baseline-partition] loaded cached sample partition data: {data_cache_path}", flush=True)
        return cached

    node_idx = _deterministic_balanced_node_sample(data, max_nodes)
    partitioned = _induce_partition_data(data, node_idx, dataset_name, cluster_count, cluster_id)
    if data_cache_path is not None:
        torch.save(partitioned, data_cache_path)
    return partitioned


def _partition_data_cache_path(data_root: str, dataset_name: str) -> Path | None:
    mode = os.environ.get("BASELINE_PARTITION_MODE", "none").strip().lower()
    if mode in ("", "none", "false", "0", "off"):
        return None
    cluster_count = int(os.environ.get("BASELINE_PARTITION_COUNT", scaffold_cluster_count(dataset_name)))
    cluster_id = int(os.environ.get("BASELINE_PARTITION_ID", "0"))
    max_nodes = int(os.environ.get("BASELINE_PARTITION_MAX_NODES", "12000"))
    edge_sample_size = int(os.environ.get("BASELINE_PARTITION_EDGE_SAMPLE_SIZE", "5000000"))
    force_single = os.environ.get("BASELINE_FORCE_SINGLE_LABEL", "0") in ("1", "true", "TRUE", "yes")
    cache_root = Path(os.environ.get("BASELINE_PARTITION_CACHE_ROOT", data_root))
    method = os.environ.get("BASELINE_METHOD_NAME", "shared").strip().lower() or "shared"
    cache_dir = cache_root / method / "partitions"
    cache_dir.mkdir(parents=True, exist_ok=True)
    canonical = canonical_baseline_dataset_name(dataset_name)
    label_tag = "_singlelabel" if force_single else ""
    mode_tag = mode.replace("-", "")
    return cache_dir / (
        f"{canonical}_{mode_tag}_parts{cluster_count}_id{cluster_id}_max{max_nodes}_sample{edge_sample_size}{label_tag}_data.pt"
    )


def _load_cached_partition_data(data_root: str, dataset_name: str) -> Data | None:
    cache_path = _partition_data_cache_path(data_root, dataset_name)
    if cache_path is None:
        return None
    if not cache_path.exists() and os.environ.get("BASELINE_FORCE_SINGLE_LABEL", "0") in ("1", "true", "TRUE", "yes"):
        original_force = os.environ.get("BASELINE_FORCE_SINGLE_LABEL")
        os.environ["BASELINE_FORCE_SINGLE_LABEL"] = "0"
        try:
            multi_label_path = _partition_data_cache_path(data_root, dataset_name)
        finally:
            if original_force is None:
                os.environ.pop("BASELINE_FORCE_SINGLE_LABEL", None)
            else:
                os.environ["BASELINE_FORCE_SINGLE_LABEL"] = original_force
        if multi_label_path is not None and multi_label_path.exists():
            data = _torch_load_trusted_cache(multi_label_path)
            if data.y is not None and data.y.dim() > 1 and data.y.size(-1) > 1:
                data.y = data.y.argmax(dim=-1)
            torch.save(data, cache_path)
    if not cache_path.exists():
        return None
    data = _torch_load_trusted_cache(cache_path)
    print(f"[baseline-partition] loaded cached partition data: {cache_path}", flush=True)
    return data


def _metis_partition(data: Data, cluster_count: int, edge_sample_size: int = 0) -> torch.Tensor:
    num_nodes = int(data.num_nodes)
    # METIS/ClusterData expects an undirected graph.  Always symmetrize before
    # partitioning so directed datasets such as ogbn-arxiv do not get a directed
    # partitioning artifact.
    edge_index = to_undirected(data.edge_index.cpu(), num_nodes=num_nodes)
    if edge_sample_size > 0:
        generator = torch.Generator(device="cpu")
        generator.manual_seed(int(os.environ.get("BASELINE_PARTITION_SEED", "123")))
        sample_idx = torch.randint(edge_index.size(1), (edge_sample_size,), generator=generator)
        edge_index = edge_index[:, sample_idx].contiguous()
        print(
            "[baseline-partition] "
            f"sampling {edge_sample_size} edges for METIS from {data.edge_index.size(1)} total edges",
            flush=True,
        )

    num_parts = min(max(1, int(cluster_count)), num_nodes)
    try:
        return _metis_partition_sparse_tensor(edge_index, num_nodes, num_parts)
    except Exception as sparse_exc:
        print(f"[baseline-partition] SparseTensor METIS failed; falling back to ClusterData: {sparse_exc}", flush=True)

    try:
        from torch_geometric.loader import ClusterData
    except Exception as exc:
        raise ImportError("METIS smoke partitioning requires torch_sparse or torch_geometric.loader.ClusterData.") from exc

    kwargs = {
        "num_parts": num_parts,
        "recursive": False,
        "save_dir": None,
        "log": False,
    }
    import inspect

    if "keep_inter_cluster_edges" in inspect.signature(ClusterData).parameters:
        kwargs["keep_inter_cluster_edges"] = True

    cluster_data = ClusterData(Data(edge_index=edge_index, num_nodes=num_nodes), **kwargs)
    return _partition_from_partptr_perm(cluster_data.partptr.cpu(), cluster_data.perm.cpu(), num_nodes, num_parts)


def _metis_partition_sparse_tensor(edge_index: torch.Tensor, num_nodes: int, num_parts: int) -> torch.Tensor:
    from torch_sparse import SparseTensor

    src, dst = edge_index.long()
    adj = SparseTensor(row=src, col=dst, sparse_sizes=(num_nodes, num_nodes))
    _cluster, partptr, perm = adj.partition(num_parts, recursive=False)
    return _partition_from_partptr_perm(partptr.cpu(), perm.cpu(), num_nodes, num_parts)


def _partition_from_partptr_perm(partptr: torch.Tensor, perm: torch.Tensor, num_nodes: int, num_parts: int) -> torch.Tensor:
    part = torch.full((num_nodes,), -1, dtype=torch.long)
    for cid in range(partptr.numel() - 1):
        part[perm[partptr[cid] : partptr[cid + 1]]] = cid
    missing = part < 0
    if bool(missing.any()):
        part[missing] = torch.arange(int(missing.sum()), dtype=torch.long) % max(1, int(num_parts))
    return part


def _balanced_partition_sample(data: Data, node_idx: torch.Tensor, max_nodes: int) -> torch.Tensor:
    masks = [data.train_mask.cpu(), data.val_mask.cpu(), data.test_mask.cpu()]
    buckets = []
    remaining = set(node_idx.tolist())
    per_bucket = max(1, max_nodes // max(1, len(masks)))
    for mask in masks:
        chosen = node_idx[mask[node_idx]]
        if chosen.numel() > per_bucket:
            chosen = chosen[:per_bucket]
        buckets.append(chosen)
        remaining.difference_update(chosen.tolist())

    selected = torch.unique(torch.cat([b for b in buckets if b.numel() > 0])) if buckets else torch.empty(0, dtype=torch.long)
    if selected.numel() < max_nodes and remaining:
        fill = torch.tensor(sorted(remaining)[: max_nodes - selected.numel()], dtype=torch.long)
        selected = torch.unique(torch.cat([selected, fill]))
    return selected[:max_nodes]


def _deterministic_balanced_node_sample(data: Data, max_nodes: int) -> torch.Tensor:
    n = int(data.num_nodes)
    if n <= max_nodes:
        return torch.arange(n, dtype=torch.long)

    generator = torch.Generator(device="cpu")
    base_seed = int(os.environ.get("BASELINE_PARTITION_SEED", "123"))
    partition_id = int(os.environ.get("BASELINE_PARTITION_ID", "0"))
    generator.manual_seed(base_seed + 1000003 * partition_id)
    masks = [
        getattr(data, "train_mask", torch.zeros(n, dtype=torch.bool)).cpu().bool(),
        getattr(data, "val_mask", torch.zeros(n, dtype=torch.bool)).cpu().bool(),
        getattr(data, "test_mask", torch.zeros(n, dtype=torch.bool)).cpu().bool(),
    ]
    per_bucket = max(1, max_nodes // max(1, len(masks)))
    chosen_parts = []
    chosen_mask = torch.zeros(n, dtype=torch.bool)
    for mask in masks:
        candidates = torch.where(mask)[0]
        if candidates.numel() == 0:
            continue
        take = min(per_bucket, int(candidates.numel()), max_nodes - int(chosen_mask.sum()))
        if take <= 0:
            break
        perm = torch.randperm(candidates.numel(), generator=generator)[:take]
        selected = candidates[perm]
        chosen_parts.append(selected)
        chosen_mask[selected] = True

    remaining_slots = max_nodes - int(chosen_mask.sum())
    if remaining_slots > 0:
        remaining = torch.where(~chosen_mask)[0]
        take = min(remaining_slots, int(remaining.numel()))
        if take > 0:
            perm = torch.randperm(remaining.numel(), generator=generator)[:take]
            chosen_parts.append(remaining[perm])

    if not chosen_parts:
        return torch.arange(min(max_nodes, n), dtype=torch.long)
    return torch.unique(torch.cat(chosen_parts)).long()[:max_nodes]


def _induce_partition_data(data: Data, node_idx: torch.Tensor, dataset_name: str, cluster_count: int, cluster_id: int) -> Data:
    node_idx = node_idx.cpu().long()
    edge_index, edge_attr = subgraph(node_idx, data.edge_index.cpu(), getattr(data, "edge_attr", None), relabel_nodes=True)
    out = Data(
        x=data.x.cpu()[node_idx],
        edge_index=edge_index.long(),
        y=data.y.cpu()[node_idx] if data.y is not None else None,
        num_nodes=int(node_idx.numel()),
    )
    if edge_attr is not None:
        out.edge_attr = edge_attr
    if getattr(data, "edge_index_is_undirected_unique", False):
        out.edge_index_is_undirected_unique = True
    out.train_mask = data.train_mask.cpu()[node_idx].bool()
    out.val_mask = data.val_mask.cpu()[node_idx].bool()
    out.test_mask = data.test_mask.cpu()[node_idx].bool()
    _ensure_nonempty_masks(out)
    out.baseline_partition_info = {
        "dataset": dataset_name,
        "cluster_count": int(cluster_count),
        "cluster_id": int(cluster_id),
        "original_num_nodes": int(data.num_nodes),
        "partition_num_nodes": int(out.num_nodes),
    }
    print(
        "[baseline-partition] "
        f"dataset={dataset_name} cluster_count={cluster_count} cluster_id={cluster_id} "
        f"nodes={out.num_nodes}/{data.num_nodes} edges={out.edge_index.size(1)}/{data.edge_index.size(1)}"
    )
    return out


def _ensure_nonempty_masks(data: Data) -> None:
    masks = [data.train_mask, data.val_mask, data.test_mask]
    if all(int(mask.sum()) > 0 for mask in masks):
        return
    n = int(data.num_nodes)
    if n == 0:
        raise RuntimeError("Partition smoke adapter produced an empty subgraph.")
    idx = torch.arange(n)
    train_end = max(1, int(0.6 * n))
    val_end = max(train_end + 1, int(0.8 * n)) if n > 2 else train_end
    data.train_mask = torch.zeros(n, dtype=torch.bool)
    data.val_mask = torch.zeros(n, dtype=torch.bool)
    data.test_mask = torch.zeros(n, dtype=torch.bool)
    data.train_mask[idx[:train_end]] = True
    if val_end > train_end:
        data.val_mask[idx[train_end:val_end]] = True
    else:
        data.val_mask[idx[:1]] = True
    if val_end < n:
        data.test_mask[idx[val_end:]] = True
    else:
        data.test_mask[idx[-1:]] = True


def load_dense_tensors(data_root: str, dataset_name: str):
    data, _dataset = load_pyg_data(data_root, dataset_name)
    if data.num_nodes > int(os.environ.get("BASELINE_DENSE_MAX_NODES", "100000")):
        raise RuntimeError(
            f"{dataset_name} has {data.num_nodes} nodes; this dense baseline adapter is intended "
            "for small full-graph smoke tests. Use a sparse/minibatch path for full-scale runs."
        )
    from torch_geometric.utils import to_dense_adj

    adj = to_dense_adj(data.edge_index, max_num_nodes=data.num_nodes)[0]
    if adj.size(0) < data.num_nodes or adj.size(1) < data.num_nodes:
        padded = adj.new_zeros((data.num_nodes, data.num_nodes))
        padded[: adj.size(0), : adj.size(1)] = adj
        adj = padded
    idx_train = torch.where(data.train_mask)[0]
    idx_val = torch.where(data.val_mask)[0]
    idx_test = torch.where(data.test_mask)[0]
    labels = data.y
    if labels.dim() > 1 and labels.size(-1) > 1:
        labels = labels.argmax(dim=-1)
    return adj, data.x.float(), labels.long(), idx_train, idx_val, idx_test


def infer_embedding_dim(data_root: str, dataset_name: str, hidden_dim: int = 512):
    data, _dataset = load_pyg_data(data_root, dataset_name)
    labels = data.y
    if labels.dim() > 1 and labels.size(-1) > 1:
        out_dim = int(labels.size(-1))
    else:
        valid_labels = labels[labels >= 0]
        out_dim = int(valid_labels.max().item() + 1)
    return [int(data.x.size(1)), int(hidden_dim), out_dim]
